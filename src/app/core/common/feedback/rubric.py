from __future__ import annotations

import inspect

# 1:1 / N:1 채점 프롬프트가 함께 쓰는 축별 등급 기준.
# 점수 계산(가중치·반올림)은 scoring.py 가 하고, 모델은 이 기준으로 등급만 고른다.
# 등급 문구를 바꾸면 scoring.SCORING_VERSION 도 올린다 — 같은 답변의 점수가 달라지기 때문이다.
AXIS_LEVEL_CRITERIA = inspect.cleandoc(
    """
    [축별 등급 기준]
    문항마다 네 축의 등급을 0~4 정수로 매긴다. 점수는 서버가 등급으로 계산하므로 점수를 직접 매기지 마라.
    - 인접한 등급은 아래 조건 하나 차이로 가른다. 조건을 대조해 가장 잘 맞는 등급을 고른다.
    - 질문이 요구한 범위 안에서 판단한다. 질문이 요구하지 않은 요소(예: 이유만 물은 질문의 대안 비교)는
      빠져 있어도 등급을 낮추지 않고, 그 요소를 뺀 나머지 조건으로 등급을 고른다.
    - 문장력, 답변 길이, 구어체, 말버릇은 어느 축에도 반영하지 않는다.
    - FOLLOW 문항은 부모 답변까지 합쳐서 판단한다.
    - 3등급 이하인 축이 있으면 그 이유가 해당 문항의 improvements에 드러나게 쓴다.

    intent — 의도 충족: 물은 것에 답했는가
    - 4: 질문이 요구한 핵심 요소에 모두 직접 답했다.
    - 3: 핵심에는 답했으나 부차적 요소 하나를 빠뜨렸다.
    - 2: 핵심 요소 중 일부에만 답했다.
    - 1: 관련 주제를 말했지만 물은 것에는 답하지 않았다.
    - 0: 질문과 무관하거나 답을 회피했다. 이 경우 나머지 축도 모두 0으로 한다.

    depth — 깊이: 왜 그렇게 했는가
    - 4: 이유와 함께 대안 비교(트레이드오프), 한계나 적용 조건까지 설명했다.
    - 3: 이유와 함께 대안 비교나 한계 중 하나를 설명했다.
    - 2: 구체적인 이유를 제시했으나 비교나 한계 인식은 없다.
    - 1: '많이 써서', '좋아서' 수준의 일반론적 이유만 있다.
    - 0: 이유 설명이 없다.

    specificity — 구체성: 무엇을, 어떻게 했는가
    - 4: 본인이 한 일을 구현 방식·대상과 그 결과(관찰된 효과)까지 설명했다.
    - 3: 구현 방식·대상은 구체적이나 결과나 본인 역할이 불분명하다.
    - 2: 무엇을 했는지는 말했으나 어떻게 했는지가 없다.
    - 1: 교과서식 일반 설명뿐이고 본인 경험이 드러나지 않는다.
    - 0: 구체적 내용이 없다.

    accuracy — 정확성: 확립된 기술 개념과 맞는가
    - 4: 기술적 오류가 없다.
    - 3: 용어 혼용처럼 결론에 영향 없는 사소한 부정확함이 있다.
    - 2: 일부 설명이 틀려 답의 일부가 잘못됐다.
    - 1: 핵심 설명이 틀렸다.
    - 0: 대부분의 기술 설명이 틀렸다.
    - null: 기술 내용이 없는 질문이다.
    프로젝트 구현, 경험, 성과처럼 확인할 수 없는 주장은 정확성 판단 대상이 아니다.

    consistency — 일관성: 면접 전체에서 한 번만 매긴다(overall.consistency)
    - 4: 답변 간 어긋나는 진술이 없다.
    - 3: 표현만 다르고 양립 가능한 불일치가 있다.
    - 2: 세부 사항(순서, 세부 수치)이 1건 어긋난다.
    - 1: 핵심 사실(역할, 기술 선택, 원인)이 1건 어긋난다.
    - 0: 핵심 사실이 2건 이상 어긋난다.
    - null: 답변이 1개뿐이라 비교할 대상이 없다.
    근거가 부족한 것은 모순이 아니다. 근거 부족은 specificity에서 판단한다.
    """
)
