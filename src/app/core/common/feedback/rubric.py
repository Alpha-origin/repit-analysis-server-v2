from __future__ import annotations

import inspect

# 1:1 / N:1 채점 프롬프트가 함께 쓰는 축별 등급 기준.
# 점수 계산(가중치·반올림)은 scoring.py 가 하고, 모델은 이 기준으로 등급만 고른다.
# 등급 문구를 바꾸면 scoring.SCORING_VERSION 도 올린다 — 같은 답변의 점수가 달라지기 때문이다.
AXIS_LEVEL_CRITERIA = inspect.cleandoc(
    """
    [축별 등급 기준]
    문항마다 네 축의 등급을 0~4 정수로 매긴다. 점수는 서버가 등급으로 계산하므로 점수를 직접 매기지 마라.

    [판정 순서 — 모든 문항에 동일하게 적용]
    1. 질문과 질문 의도에서 명시적으로 요구한 항목만 정한다.
       이유, 대안, 한계, 수치, 본인 역할을 질문이 요구하지 않았다면 필수 항목에 추가하지 마라.
       하나의 요구를 잘게 쪼개 누락 항목을 늘리지 마라. 질문 의도는 질문 범위를 설명하는 자료다.
    2. 각 요구에 대응하는 실제 답변 문구를 확인한다. FOLLOW는 부모 답변도 함께 확인한다.
       암묵적인 의도, 일반적인 모범답안, 다른 문항의 답변으로 현재 답변의 부족한 근거를 채우지 마라.
    3. intent는 요구 충족 여부, depth는 실제 이유 설명, specificity는 실제 구체성,
       accuracy는 확인 가능한 기술 주장으로 각각 따로 결정한다.
       이유·대안·결과가 없다는 이유만으로 intent까지 함께 낮추지 마라.
    4. 아래 조건을 높은 등급부터 대조하고, 필요한 근거가 모두 있는 첫 등급을 고른다.
       높은 등급의 근거가 없으면 바로 아래 조건으로 내려간다. 인상이나 답변 길이로 보정하지 마라.
    5. strengths와 improvements에 실제 답변의 짧은 문구와 판정 이유를 연결한다.
       필수 요구 누락과 추가로 발전시키면 좋은 설명을 구분한다.
       질문이 요구하지 않은 추가 설명을 '질문에 답하지 못했다'는 근거로 쓰지 마라.
       이미 답한 항목은 누락이라고 쓰지 마라. 예시 답안에 새로 쓴 내용을 채점 근거로 쓰지 마라.

    문장력, 답변 길이, 구어체, 말버릇은 어느 축에도 반영하지 않는다.
    다른 문항과의 모순은 consistency에서 판단하며, 해당 문항 자체의 등급을 임의로 낮추지 않는다.

    intent — 의도 충족: 물은 것에 답했는가
    - 4: 명시적으로 요구한 항목을 모두 답했다. 요구가 하나면 그 하나에 직접 답한 짧은 답변도 4다.
    - 3: 명시적인 요구가 3개 이상이고, 정확히 1개만 답하지 않았다.
    - 2: 요구 중 적어도 하나에는 답했으나 4나 3의 조건을 충족하지 않는다.
    - 1: 관련 주제를 언급했으나 요구한 항목에 실질적으로 답한 것이 없다.
    - 0: 관련 내용도 없거나 답변 전체가 거절·회피뿐이다. 나머지 축도 모두 0으로 한다.
    단순히 질문의 단어를 반복한 것은 항목 충족이 아니다.
    확립된 기술 개념을 정반대로 설명한 항목은 충족으로 세지 않는다.
    기술 용어를 언급했다는 이유만으로 1을 2로 올리지 마라.

    depth — 깊이: 왜 그렇게 했는가
    먼저 다음 세 근거의 존재를 각각 확인한다.
    R: 특정 문제·제약·목표와 선택을 연결한 이유. '그 방법을 썼다'는 행동만으로 R을 추정하지 마라.
       문제의 원인을 밝히고 그 원인을 제거하는 수정 방법을 연결했다면 R로 인정한다.
       '때문에'라는 단어 유무로 판단하지 마라. 측정했다는 절차만으로는 R이 생기지 않는다.
    A: 둘 이상의 대안을 실제로 비교하고 차이나 선택 기준을 설명함. 대안 이름 나열은 제외한다.
    L: 선택한 방식의 한계나 적용 조건을 구체적으로 설명함. '한계가 있다'는 말만으로는 인정하지 않는다.
    - 4: R, A, L이 모두 있다.
    - 3: R이 있고 A와 L 중 정확히 하나가 있다.
    - 2: R만 있다.
    - 1: R은 없고 '많이 써서', '좋아서' 같은 일반적인 이유만 있다.
    - 0: 이유 설명 자체가 없다. 행동·수치·측정 절차만 있는 답변을 이유 설명으로 세지 마라.
    이유를 요구하지 않은 질문에서도 이 축은 실제 제시된 이유를 평가한다.
    이 축의 부족함을 intent의 누락으로 옮기지 말고, 개선 제안은 추가 설명으로 안내한다.

    specificity — 구체성: 무엇을, 어떻게 했는가
    질문 유형은 기술 원리 설명, 단일 사실 확인, 구현·경험 순서로 구분해 한 기준만 적용한다.
    기술 원리의 동작을 설명하는 질문에는 다음 조건을 적용한다.
    - 4: 동작 관계와 진행 순서·조건을 함께 구체적으로 설명했다.
    - 3: 구성 요소가 어떤 동작을 하는지 관계를 설명했으나 순서·조건 설명은 없다.
    - 2: 구성 요소나 상태만 나열했다.
    - 1: 기술 용어만 언급했다.
    - 0: 관련 동작 설명이 없다.
    동작 설명의 기술적 오류는 accuracy에서 판단하고, 설명의 구체성과 혼동하지 마라.
    단일 대상·역할·시점·수치를 확인하는 질문에는 다음 조건을 적용한다.
    - 4: 요구한 대상이나 값을 특정했다. 구현 방법·성과를 추가로 요구하지 마라.
    - 3: 대상 범위는 좁혔으나 요구한 식별 정보 하나가 불명확하다.
    - 2: 넓은 범주만 말했다.
    - 1: '적절한 곳', '중요한 것' 같은 추상적인 표현만 있다.
    - 0: 관련 대상이나 값이 없다.
    구현·경험·해결 과정 질문에는 다음 조건을 높은 등급부터 적용한다.
    - 4: 한 일, 구체적인 방법, 실제 관찰된 결과가 모두 있다. 결과는 정성적 변화도 인정한다.
    - 3: 한 일과 구체적인 방법은 있으나 실제 관찰된 결과가 없다.
    - 2: 한 일이나 적용 대상은 있으나 방법이 없다. 사용한 도구 이름만으로 방법을 인정하지 마라.
    - 1: 일반적인 방침·의견만 있고 실제 행동이나 방법은 없다.
    - 0: 구체적인 관련 내용이 없다.
    '했습니다'로 서술한 행동에 '제가'라는 단어가 없다고 역할 불명확으로 낮추지 마라.
    '측정·비교했다'는 검증 방법이지 개선 결과 자체가 아니다. 결과 수치를 추측해서 보충하지 마라.

    accuracy — 정확성: 확립된 기술 개념과 맞는가
    실제 답변에서 기술 원리에 관한 검증 가능한 주장만 추출한다.
    - 4: 그 주장들에 기술적 오류가 없다.
    - 3: 결론과 동작은 맞으며 용어 혼용 같은 사소한 오류만 있다.
    - 2: 핵심 동작은 맞으나 부가 설명 일부가 틀렸다.
    - 1: 질문의 핵심 동작·개념을 틀리게 설명했다.
    - 0: 독립적인 기술 주장 2개 이상이 있고 모두 틀렸다.
    - null: 검증 가능한 기술 원리 주장이 없다.
    기술 설명이 하나이고 그 핵심이 틀렸다면 1이다. 그 설명을 임의로 쪼개 0으로 바꾸지 마라.
    특정 프로젝트의 사용 값·담당 역할·성과는 확인할 수 없으므로 기술 원리 주장으로 세지 않는다.
    정보가 부족하다는 이유로 정확성을 낮추거나, 기술 오류 근거 없이 3을 주지 마라.

    consistency — 일관성: 면접 전체에서 한 번만 매긴다(overall.consistency)
    - 4: 답변 간 어긋나는 진술이 없다.
    - 3: 표현만 다르고 양립 가능한 불일치가 있다.
    - 2: 세부 사항(순서, 세부 수치)이 1건 어긋난다.
    - 1: 핵심 사실(역할, 기술 선택, 원인)이 1건 어긋난다.
    - 0: 핵심 사실이 2건 이상 어긋난다.
    - null: 답변이 1개뿐이라 비교할 대상이 없다.
    근거가 부족한 것은 모순이 아니다. 근거 부족은 specificity에서 판단한다.
    """
)
