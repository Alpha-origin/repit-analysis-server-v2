        "그 둘에 해당하는 실제 코드를 파일 트리에서 골라 read_files로 열어 분석하라.\n"
        "분석이 끝나면 generate_result로 결과를 제출하라.\n"
        "제출할 때는 project_summary(overview·repositories·core_features·tech_stack) 와\n"
        "interview 5문항을 [산출물 형식] 그대로 빠짐없이 채워라."
